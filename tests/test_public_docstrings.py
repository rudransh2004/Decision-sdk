"""Every public symbol of the SDK has a hand-written docstring."""

import inspect

import pytest

import futurix_decision
import futurix_decision.client
import futurix_decision.errors


def public_symbols():
    for module in (futurix_decision, futurix_decision.client):
        for name in module.__all__:
            yield f"{module.__name__}.{name}", getattr(module, name)
    for name, obj in vars(futurix_decision.errors).items():
        if inspect.isclass(obj) and obj.__module__ == futurix_decision.errors.__name__:
            yield f"futurix_decision.errors.{name}", obj


@pytest.mark.parametrize(("path", "symbol"), list(public_symbols()), ids=lambda value: str(value))
def test_symbol_has_a_docstring(path, symbol):
    doc = (inspect.getdoc(symbol) or "").strip() if inspect.isroutine(symbol) else ""
    if inspect.isclass(symbol):
        # A class's own docstring, not one inherited from a base or generated by @dataclass.
        doc = (symbol.__dict__.get("__doc__") or "").strip()
        assert not doc.startswith(f"{symbol.__name__}("), f"{path} has only a generated docstring"
    assert doc, f"{path} has no docstring"
